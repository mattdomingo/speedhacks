// Regenerates backend/analytics/keewano-events.generated.mjs from keewano.events.json.
// Keewano's codegen emits TypeScript; Node's built-in type stripping turns it into plain ESM.
// Usage: npm run keewano:codegen [-- --check]
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const input = join(root, 'backend/analytics/keewano.events.json');
const output = join(root, 'backend/analytics/keewano-events.generated.mjs');
const scratch = mkdtempSync(join(tmpdir(), 'keewano-codegen-'));
try {
  execFileSync(process.execPath, [join(root, 'node_modules/@keewano/codegen/bin/keewano-codegen.cjs'),
    '--input', input, '--target', 'node', '--code', scratch], { stdio: 'pipe' });
  const source = readFileSync(join(scratch, 'keewano-events.generated.ts'), 'utf8');
  const generated = '// AUTO-GENERATED by @keewano/codegen from keewano.events.json. DO NOT EDIT.\n' +
    '// Append events there (never reorder: ids are positional), then run `npm run keewano:codegen`.\n' +
    stripTypeScriptTypes(source, { mode: 'transform' });
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== generated) {
      console.error('keewano-events.generated.mjs is stale; run npm run keewano:codegen');
      process.exitCode = 1;
    }
  } else {
    writeFileSync(output, generated);
    console.log(`Wrote ${output}`);
  }
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
